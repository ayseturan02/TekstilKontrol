const fs=require('node:fs'),path=require('node:path'),babel=require('@babel/core');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'shared/paperScript.source.js'),'utf8');
const code=babel.transformSync(source,{presets:[['@babel/preset-env',{targets:{chrome:'74'},modules:false}]],configFile:false,babelrc:false,comments:false,compact:true}).code.replace(/;\s*$/,'');
fs.writeFileSync(path.join(root,'shared/paperScript.js'),'// Generated by npm run build:paper. Keep browser code literal for Hermes.\nmodule.exports = '+JSON.stringify(code)+';\n','utf8');
